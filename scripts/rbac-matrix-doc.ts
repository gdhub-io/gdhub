/**
 * Renders the permission matrix into docs/roles-and-permissions-matrix.md.
 *
 *   bun run rbac:matrix-doc
 *
 * Generated from the space registry, i.e. from the same source the seed writes
 * to the database — so the document cannot drift from the code. What it does not
 * show are hand-made edits in the admin UI; those live only in the database.
 */
import { writeFileSync } from "node:fs";
import { ACTION_CLASS } from "@/config/permissions/actions";
import {
	buildPermissionMatrix,
	matrixLookup,
} from "@/config/permissions/matrix";
import { SPACE_ROLES } from "@/config/permissions/roles";
import { spaceList } from "@/config/spaces";
import { permissionsOf } from "@/config/spaces/define-space";

const SPACE_TITLES: Record<string, string> = {
	hub: "hub — the community",
	project: "project space",
	event: "event space",
	course: "course space",
	admin: "admin — running the platform",
	dev: "dev — development tools",
};

const CLASS_TITLES: Record<string, string> = {
	read: "read & take part",
	manage: "manage",
	destructive: "irreversible",
};

const spaces = spaceList();
const lookup = matrixLookup(buildPermissionMatrix(spaces));

const cell = (role: string, permission: string): string => {
	const state = lookup.get(`${role}:${permission}`);

	if (!state?.allowed) return "—";

	return state.scope === "own" ? "`own`" : "✅";
};

const lines: string[] = [
	"# Permission matrix",
	"",
	"> Generated by `bun run rbac:matrix-doc` from the space registry",
	"> ([src/config/spaces](../src/config/spaces)). Do not edit by hand — the next",
	"> run overwrites it.",
	">",
	"> These are the **defaults from code**: what the seed writes into",
	"> `SpaceRolePermission`. Checkboxes changed afterwards in the admin UI live",
	"> only in the database and are not shown here.",
	"",
	"Legend: ✅ allowed, `own` limited to the user's own records, — denied.",
	"",
	"Entering a space is not guarded by a permission — any role gets you in",
	"(docs/roles-and-permissions.md §3.1).",
	"",
]

for (const space of spaces) {
	lines.push(`## ${SPACE_TITLES[space.type] ?? space.type}`, "");
	lines.push(`| Permission | ${SPACE_ROLES.join(" | ")} | Class |`);
	lines.push(`|---|${SPACE_ROLES.map(() => "---").join("|")}|---|`);

	let previousFeature = "";

	for (const permission of permissionsOf(space)) {
		const [, feature, action] = permission.split(".");

		if (feature !== previousFeature && previousFeature) lines.push("| | | | | | |");
		previousFeature = feature;

		const cells = SPACE_ROLES.map((role) => cell(role, permission)).join(" | ");
		lines.push(
			`| \`${permission}\` | ${cells} | ${CLASS_TITLES[ACTION_CLASS[action as never]] ?? ""} |`,
		);
	}

	const inherits = space.inheritRoleFrom;
	lines.push("");

	if (inherits) {
		lines.push(
			`Role is inherited from the \`${inherits.space}\` space, from \`${inherits.atLeast}\` upwards.`,
			"",
		);
	}
}

lines.push(
	"## Who gets which role",
	"",
	"| Space | owner | admin | member | guest |",
	"|---|---|---|---|---|",
	"| `hub` | owns the hub | platform staff | finished onboarding | just signed up |",
	"| `project` | the author (also the `Founder`) | invited manager | hired team member | by invitation only |",
	"| `event` | the creator | invited manager | approved participant | by invitation only |",
	"| `course` | the author | teacher | enrolled student | by invitation only |",
	"| `admin` | inherited from `hub.owner` | inherited from `hub.admin` | — | — |",
	"| `dev` | inherited from `hub.owner` | inherited from `hub.admin` | — | — |",
	"",
	"A hub role does **not** open somebody else's project, event or course. That",
	"line is crossed only by the super-admin (`User.isSuperAdmin`), and such",
	"actions are written to the audit log.",
	"",
);

writeFileSync("docs/roles-and-permissions-matrix.md", `${lines.join("\n")}\n`);

console.info(
	`docs/roles-and-permissions-matrix.md: ${spaces.length} spaces, ${lookup.size} cells`,
);
